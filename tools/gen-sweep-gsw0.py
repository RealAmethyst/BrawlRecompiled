"""Derive per-area GSW(0) (story progress) values for map sweeps from the game's own evt scripts.

Reads game\\spm_linked.rel (linked REL image at 0x80BF6840), walks every evt script in .data, attributes each script to a
map by its debug-name op (0x72, e.g. "mi1_01_init_evt"), and collects the GSW(0) thresholds (GSW(0) = 0xF5DE0180) its
map scripts test or set. Per sub-area (he1, mi2, ...) it picks the highest threshold inside that chapter's GSW range, so
every intro/cutscene branch of that sub-area is already past. Chapter ranges come from the game's own chapter switch
(case < 54 / 96 / 126 / 174 / 221 / 287 / 354 / 421, used by mac_03, he2_02 ...). Writes tools\\sweep-gsw0.txt.
Usage: python tools\\gen-sweep-gsw0.py
"""
import collections, re, struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
b = (ROOT / 'game' / 'spm_linked.rel').read_bytes()
BASE, RODATA, DATA, BSS = 0x80BF6840, 0x80C5A658, 0x80CA5B40, 0x80F12640  # game\spm_rel_layout.json sections 4/5/6
GSW0 = 0xF5DE0180
W = lambda a: struct.unpack_from('>I', b, a - BASE)[0]
# chapter -> [lo, hi) GSW(0) range; lo of chapter 1 = 11 (ls4_11/mac_22 switch: case < 11 = prologue)
CHAPTERS = {'he': (11, 54), 'mi': (54, 96), 'ta': (96, 126), 'sp': (126, 174), 'gn': (174, 221), 'wa': (221, 287),
            'an': (287, 354), 'ls': (354, 421)}
# value from a test that is false / branch that is past at that value: x < X -> X, x <= X -> X+1, x >= X -> X, x > X -> X+1, SET X -> X
PAST = {0x1A: 0, 0x1B: 1, 0x1C: 1, 0x1D: 0, 0x32: 0, 0x26: 0, 0x27: 1, 0x28: 1, 0x29: 0}

found = collections.defaultdict(set)
sets = collections.defaultdict(set)
mapname = None
for a in range(DATA, BSS - 8, 4):
    h = W(a)
    if h == 0x00010072 and RODATA <= W(a + 4) < DATA:  # evt debug name
        o = W(a + 4) - BASE
        m = re.match(rb'([a-z]{2,3}[0-9]?_[0-9]{2})', b[o:o + 16])
        mapname = m.group(1).decode() if m else mapname
        continue
    if not mapname:
        continue
    vals = []
    if h == GSW0 and (W(a - 4) & 0xFFFF) in PAST and W(a - 4) >> 16 == 2:  # if_*/set with 2 args, GSW(0) first
        vals.append(W(a + 4) + PAST[W(a - 4) & 0xFFFF])
        if W(a - 4) == 0x00020032:
            sets[mapname].add(W(a + 4))
    if h == GSW0 and W(a - 4) == 0x00010022:  # switch GSW(0): following case_* ops up to end_switch
        p = a + 4
        for _ in range(80):
            op, n = W(p) & 0xFFFF, W(p) >> 16
            if op in (0x30, 0x31) or n > 8:
                break
            if op in PAST and op >= 0x26 and n == 1:
                vals.append(W(p + 4) + PAST[op])
            p += 4 + 4 * n
    found[mapname].update(v for v in vals if v < 1000)

inrange = lambda name, vals: {v for v in vals if CHAPTERS.get(name[:2], (0, 0))[0] <= v < CHAPTERS.get(name[:2], (0, 0))[1]}
areas = collections.defaultdict(set)  # sub-area default: highest progress its own events SET = state after finishing it
for name, vals in sets.items():
    areas[name[:3]].update(inrange(name, vals))

lines = ['# Per-map GSW(0) for map sweeps (SPM_SWEEP_GSW0_TABLE=tools\\sweep-gsw0.txt). "prefix value", longest prefix wins;',
         '# maps matching nothing use SPM_SWEEP_GSW0 (default: leave the save alone). Generated by tools\\gen-sweep-gsw0.py:',
         '# map line = highest GSW(0) threshold that map\'s own evt scripts test/set inside its chapter range (past every',
         '# intro/cutscene branch of the map); sub-area line (he1 ...) = highest value its maps SET (state after finishing',
         '# it), or the previous sub-area\'s value when it sets none.']
for ch, (lo, hi) in CHAPTERS.items():
    lines.append(f'# chapter {ch}: GSW(0) range [{lo},{hi}) from the game\'s chapter switch')
    prev = lo
    for sub in range(1, 5):
        vals = areas.get(f'{ch}{sub}')
        prev = max(vals) if vals else prev
        lines.append(f'{ch}{sub} {prev}')
        lines += [f'{m} {max(inrange(m, v))}' for m, v in sorted(found.items()) if m.startswith(f'{ch}{sub}_') and inrange(m, v)]
lines += ['# Flipside/Flopside hub: 225 = chapter 6 start (mac_22/ls4_11 switch case < 225); past every mac_* intro before',
          '# chapter 6 (mac_15 SET224) and before the chapter 6-8 hub events (mac_16 ==302/SET303).',
          'mac 225', 'dos 225',
          '# aa* (prologue/cutscene maps), dan_* (Pit), mg* (minigames), go1, bos: no GSW(0) branches worth setting -> fallback.']
(ROOT / 'tools' / 'sweep-gsw0.txt').write_text('\n'.join(lines) + '\n')
print('\n'.join(lines))
